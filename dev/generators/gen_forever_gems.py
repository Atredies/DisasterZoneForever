#!/usr/bin/env python3
"""
Writes addon/DisasterZone/Data/Gems.lua for WoW Forever: no sockets, no gems, no suggested gem / enchant guides
(Forever has no Jewelcrafting or sockets), and the enchants a Forever character can get.

The enchant records (effect id -> slot type, name, text, icon, ...; Core/Gems.lua documents them) are the TBC file's
(dev/fixtures/tbc/Data/Gems.lua, from WoWSims TBC), kept when AtlasLoot Classic Forever lists an enchant or item of
the same name anywhere (Enchanting crafts, Zandalar / Argent Dawn / Thorium rewards, scopes): its row comments carry
the names. TBC-only enchants (Outland recipes, Shattrath inscriptions, Naaru shoulder sigils) drop out that way.

Usage (from dev/):  DZ_ADDONS=<unpacked AtlasLoot> luaenv/bin/python generators/gen_forever_gems.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEV = os.path.dirname(HERE)
TBC = os.path.join(DEV, "fixtures", "tbc", "Data", "Gems.lua")
OUT = os.path.normpath(os.path.join(DEV, "..", "addon", "DisasterZone", "Data", "Gems.lua"))
MODULES = ("AtlasLootClassic_Crafting", "AtlasLootClassic_Factions", "AtlasLootClassic_PvP",
           "AtlasLootClassic_DungeonsAndRaids", "AtlasLootClassic_Collections")


def norm(s):
    s = s.lower().replace("formula:", "").replace("schematic:", "").strip()
    return re.sub(r"[^a-z0-9]+", " ", s).strip()


def main():
    al = os.environ.get("DZ_ADDONS") or (sys.argv[1] if len(sys.argv) > 1 else None)
    if not al:
        sys.exit("set DZ_ADDONS to the unpacked AtlasLoot Classic Forever folder")
    known = set()
    for m in MODULES:
        p = os.path.join(al, m, "data.lua")
        if os.path.exists(p):
            for c in re.findall(r"--\s*([^\n]+)", open(p, encoding="utf-8", errors="replace").read()):
                c = re.sub(r"\s*/\s*\d+\s*$", "", c)            # "--Enchant Cloak - Agility / 270": the skill
                known.add(norm(c))
    text = open(TBC, encoding="utf-8").read()
    i = text.index("ns.Data.Enchants = {")
    j = text.index("\n}", i)
    kept, dropped = [], 0
    for line in text[i:j].split("\n")[1:]:
        m = re.match(r'\s*\[(\d+)\] = \{ \d+, "([^"]+)"', line)
        if not m:
            continue
        if norm(m.group(2)) in known:
            kept.append(line)
        else:
            dropped += 1
    out = [
        'if DisasterZoneBoot and DisasterZoneBoot.Run("Data/Gems.lua", ...) then return end '
        '-- DisasterZone sockets, gems, enchants and suggested gems / enchants (My BiS).',
        "-- AUTO-GENERATED by gen_forever_gems.py - do not edit by hand; re-run the generator instead.",
        "-- WoW Forever: no sockets or gems (no Jewelcrafting), no suggested gem / enchant guides yet. Enchants: the TBC",
        "-- file's records (WoWSims TBC) of the enchants AtlasLoot Classic Forever lists (GPLv2), by name.",
        "local addonName, ns = ...",
        "ns.Data = ns.Data or {}",
        "",
        "ns.Data.Sockets = {}",
        "ns.Data.Gems = {}",
        "",
        "-- [enchant id] = { slot type, name, text, icon, item, spell, st = stats, et = weapon type } (Core/Gems.lua)",
        "ns.Data.Enchants = {",
    ] + kept + ["}", "", "ns.Data.GemGuides = {}", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("enchants kept %d, dropped %d (not in Forever's AtlasLoot)" % (len(kept), dropped))


if __name__ == "__main__":
    main()
