#!/usr/bin/env python3
"""Turn a DZProbe run into the facts the mock client's Forever profile uses.

  python3 dev/probe/mock_facts.py                                   # newest dev/probe/results/DZProbe-*.json
  python3 dev/probe/mock_facts.py dev/probe/results/DZProbe-X.json  # or a given run

Writes dev/tools/wowmock/forever_facts.lua (a Lua chunk returning one table). dev/tools/wowmock/forever.lua reads it
when a test client is made with forever=True. Re-run this after a new probe run and commit both files.
Standard library only.
"""
import glob
import json
import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "dev" / "tools" / "wowmock" / "forever_facts.lua"
# combat-log sub-events: the probe lists them as missing events, but they were never events
CLEU_SUB = re.compile(r"^(SPELL|SWING|RANGE|ENVIRONMENTAL)_")
# a real client global is a capitalised name; the rest of the "missing" list are local names gen_apilist.py caught
GLOBAL_NAME = re.compile(r"^[A-Z][A-Za-z0-9]+$")


def lua(v, ind=""):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "{ " + ", ".join(lua(x, ind) for x in v) + " }"
    if isinstance(v, dict):
        inner = ind + "  "
        rows = []
        for k in sorted(v):
            key = k if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", k) else "[%s]" % json.dumps(k)
            rows.append("%s%s = %s," % (inner, key, lua(v[k], inner)))
        return "{\n" + "\n".join(rows) + "\n" + ind + "}"
    raise TypeError(type(v))


def facts(run):
    s = run["static"]
    b = s["build"]
    miss = s["api"]["missing"]
    loot = s["loot"]
    r = s["restrictions"]
    return {
        "build": {"version": b["1"], "build": b["2"], "date": b["3"], "interface": b["4"]},
        "projectId": s["WOW_PROJECT_ID"],
        "projects": s["projects"],
        "expansion": s["expansion"],
        "maxLevel": s["maxLevel"],
        "removedGlobals": sorted(n for n in miss["G"] if GLOBAL_NAME.match(n)),
        "removedEvents": sorted(e for e in miss["EV"] if not CLEU_SUB.match(e)),
        "sendResults": r["sendResults"],
        "restrictionTypes": r["types"],
        "restrictionStates": r["states"],
        "lootMethods": loot["methods"],
        "lootStyles": loot["styles"],
        "lootStyle": loot["style"],
        "raidMax": loot["raidMax"],
        "combatLogForbidden": bool(s["combatLog"]["registerForbidden"]),
        "onTooltipSetItem": bool(s["tooltip"]["hasOnTooltipSetItem"]),
        "realm": s["player"]["realm"],
    }


def main(argv):
    if len(argv) > 1:
        path = argv[1]
    else:
        runs = sorted(glob.glob(str(ROOT / "dev" / "probe" / "results" / "DZProbe-*.json")))
        if not runs:
            sys.exit("no probe results in dev/probe/results/")
        path = runs[-1]
    with open(path, encoding="utf-8") as f:
        run = json.load(f)
    src = os.path.relpath(path, ROOT).replace(os.sep, "/")
    body = ("-- GENERATED by dev/probe/mock_facts.py from %s (DZProbe run %s). Do not edit: re-run the script.\n"
            "-- The WoW Forever client as measured; dev/tools/wowmock/forever.lua builds the Forever profile from it.\n"
            "return %s\n") % (src, run["static"].get("when", "?"), lua(facts(run)))
    OUT.write_text(body, encoding="utf-8")
    print("wrote %s from %s" % (os.path.relpath(OUT, ROOT), src))


if __name__ == "__main__":
    main(sys.argv)
