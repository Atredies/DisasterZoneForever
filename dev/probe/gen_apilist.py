#!/usr/bin/env python3
"""Write DZProbe/ApiList.lua: every WoW API the DisasterZone addon uses, for the probe to test in the real client.

Collects from addon/DisasterZone/**/*.lua:
  - C_Namespace.Function names
  - global names listed in dev/tools/known_globals.json that the addon calls as functions
  - event names the addon mentions as string literals (checked against known_globals' event list)

Run from the repo root or anywhere: python3 dev/probe/gen_apilist.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
ADDON = ROOT / "addon" / "DisasterZone"
KNOWN = json.loads((ROOT / "dev" / "tools" / "known_globals.json").read_text())
OUT = pathlib.Path(__file__).resolve().parent / "DZProbe" / "ApiList.lua"

src = ""
for p in sorted(ADDON.rglob("*.lua")):
    if "Libs" in p.parts:
        continue
    src += p.read_text(encoding="utf-8", errors="replace") + "\n"

cns = sorted(set(re.findall(r"\b(C_[A-Za-z0-9]+\.[A-Za-z0-9_]+)\b", src)))
calls = set(re.findall(r"(?<![\.:\w])([A-Za-z_][A-Za-z0-9_]*)\s*\(", src))
globals_used = sorted(n for n in calls if n in KNOWN["globals"])
literals = set(re.findall(r"[\"']([A-Z][A-Z0-9_]{3,})[\"']", src))
events = sorted(n for n in literals if n in KNOWN["events"])
# events the port depends on even if the TBC addon never named them
events = sorted(set(events) | {"ADDON_RESTRICTION_STATE_CHANGED", "ENCOUNTER_START", "ENCOUNTER_END",
                               "COMBAT_LOG_EVENT_UNFILTERED", "LOOT_READY", "START_LOOT_ROLL"})


def lua_list(names):
    return "{\n" + "".join(f'  "{n}",\n' for n in names) + "}"


OUT.write_text(
    "-- AUTO-GENERATED by dev/probe/gen_apilist.py from the DisasterZone source. Do not edit.\n"
    "local _, P = ...\n"
    f"P.API_C = {lua_list(cns)}\n"
    f"P.API_G = {lua_list(globals_used)}\n"
    f"P.API_EV = {lua_list(events)}\n",
    encoding="utf-8",
)
print(f"{OUT.relative_to(ROOT)}: {len(cns)} C_ functions, {len(globals_used)} globals, {len(events)} events")
